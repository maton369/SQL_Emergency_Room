-- ============================================
-- ファイル名: 06_case_return_type_error.sql
-- 目的:
--   CASE式において、各 THEN / ELSE で返す値のデータ型が
--   揃っていない場合に何が問題になるかを確認する。
--
-- テーマ:
--   CASE式は「条件に応じて1つの値を返す式」である。
--   そのため、CASE式全体として最終的にどの型の値を返すのかを
--   DBMSが決定できなければならない。
--
--   今回のSQLでは、文字列と数値が混在しているため、
--   DBMSによっては暗黙変換が行われたり、
--   期待しない型変換が起きたり、
--   場合によってはエラーになったりする。
--
--   学習上の重要点は、
--   「CASE式は見た目には分岐だが、SQLの型システム上は
--    1つの式として扱われる」
--   ということである。
-- ============================================

SELECT
    CASE
        -- ここから CASE 式を開始する。
        --
        -- CASE 式は、各行に対して条件を上から順に判定し、
        -- 最初に真になった WHEN に対応する THEN の値を返す。
        --
        -- ただし重要なのは、
        -- CASE 式全体は「1つの列の値」を作る1つの式であるため、
        -- 戻り値の型に一貫性が必要だという点である。
        --
        -- つまり、
        --   WHEN A THEN '文字列'
        --   WHEN B THEN 100
        -- のように、文字列型と数値型を混在させると、
        -- DBMSは CASE 式全体をどの型として扱うべきかを
        -- 判断しなければならない。
        --
        -- このときDBMSごとに挙動が異なることがあり、
        -- 安全なSQLを書くには、返す値の型をそろえるのが基本である。

        WHEN warehouse_id = 1 THEN 'New York'
        -- warehouse_id が 1 の場合は文字列 'New York' を返す。
        --
        -- これは文字型の値である。
        -- したがって、この分岐だけを見ると
        -- CASE 式は文字列を返すように見える。

        WHEN warehouse_id = 2 THEN 100
        -- warehouse_id が 2 の場合は数値 100 を返す。
        --
        -- ここが重要な問題点である。
        -- 直前の分岐では文字列を返していたのに対し、
        -- この分岐では整数値を返している。
        --
        -- つまり、CASE 式の戻り値候補に
        --   文字列型
        --   数値型
        -- が混在している。
        --
        -- このため、DBMSは
        --   文字列にそろえるのか
        --   数値にそろえるのか
        --   あるいはエラーにするのか
        -- を判断しなければならない。
        --
        -- DBMSによっては数値 100 を文字列 '100' に変換するかもしれないし、
        -- 逆に文字列側を数値に変換しようとして失敗する可能性もある。
        --
        -- したがって、このような混在は避けるべきである。

        WHEN warehouse_id = 3 THEN 'Los Angels'
        -- warehouse_id が 3 の場合は文字列 'Los Angels' を返す。
        --
        -- 再び文字列型に戻っている。
        -- これにより、この CASE 式の戻り値候補はさらに
        -- 「文字列・数値・文字列」と混在した状態になる。
        --
        -- なお、一般的な都市名としては
        -- 'Los Angeles' の可能性が高いため、
        -- 実データとして使う場合はスペル確認が必要である。

        WHEN warehouse_id = 4 THEN 500
        -- warehouse_id が 4 の場合は数値 500 を返す。
        --
        -- この分岐も数値型であり、
        -- warehouse_id = 2 の場合と同様に、
        -- CASE 式全体の型を不安定にする要因になっている。
        --
        -- このSQLを読むと、
        -- city 列という名前なのに数値を返すケースがあるため、
        -- 意味的にも不自然である。
        --
        -- city は本来「都市名」であり文字列で表すのが自然であるため、
        -- 500 のような数値を返す設計は、
        -- 型だけでなく列の意味の観点からも違和感がある。

        WHEN warehouse_id = 5 THEN 'San Francisco'
        -- warehouse_id が 5 の場合は文字列 'San Francisco' を返す。
        --
        -- これも文字列型であるため、
        -- CASE 式の戻り値候補は全体として
        --   文字列
        --   数値
        --   文字列
        --   数値
        --   文字列
        -- となっている。

        ELSE NULL
        -- どの条件にも一致しなかった場合は NULL を返す。
        --
        -- NULL 自体は「無値」を表す特殊な値であり、
        -- 多くのDBMSでは周囲の型文脈に従って扱われる。
        -- そのため、ELSE NULL 自体が問題になるというより、
        -- 他の THEN の戻り値の型が揃っていないことが問題になる。
        --
        -- もし全体を文字列型として扱いたいなら、
        -- NULL はその文字列型列の NULL として扱われる。
        -- 全体を数値型として扱いたいなら、
        -- 数値型列の NULL として扱われる。
    END AS city,
    -- CASE 式全体の結果に city という列名を付けている。
    --
    -- しかし今回のSQLでは、
    -- city という名前でありながら
    -- 分岐によっては数値を返している。
    --
    -- したがって、列名の意味と返却値の型・内容が
    -- 一致していない点にも注意が必要である。
    --
    -- もし本当に city 列として使うなら、
    -- すべての分岐で都市名の文字列を返すべきである。

    region
    -- 元の region 列をそのまま返す。
    --
    -- この列は CASE 式とは独立しており、
    -- Warehouse テーブルに入っている元データを表示している。

FROM Warehouse;
-- Warehouse テーブルを対象に検索する。
--
-- SQLは集合指向で実行されるため、
-- この CASE 式は Warehouse のすべての行に対して適用される。
--
-- 各行ごとに warehouse_id を見て、
-- 条件に応じた値を city 列として生成する。

-- ============================================
-- このSQLのアルゴリズム
-- ============================================
--
-- 各行に対しての処理は次の通りである。
--
-- 1. Warehouse テーブルから1行を対象にする
-- 2. その行の warehouse_id を取得する
-- 3. CASE 式の WHEN 条件を上から順に評価する
-- 4. 最初に真になった THEN の値を返す
-- 5. 返した値を city 列として出力する
-- 6. region 列も併せて表示する
--
-- ここで重要なのは、
-- 「どの値が返るか」という分岐アルゴリズムだけではなく、
-- 「返る値の型がCASE式全体で整合しているか」
-- という型システム上の要件である。
--
-- 今回の対応関係は意味的には次のようになる。
--
--   warehouse_id = 1 -> 'New York'      （文字列）
--   warehouse_id = 2 -> 100             （数値）
--   warehouse_id = 3 -> 'Los Angels'    （文字列）
--   warehouse_id = 4 -> 500             （数値）
--   warehouse_id = 5 -> 'San Francisco' （文字列）
--   その他         -> NULL
--
-- つまり、1つの列 city の中に
-- 「都市名文字列」と「整数」が混在する構造になっている。
--
-- これは、列の意味としても型としても不自然である。

-- ============================================
-- なぜ型をそろえる必要があるのか
-- ============================================
--
-- CASE 式は制御文ではなく「式」である。
-- 式である以上、最終的には1つの値を返す。
--
-- たとえば次のようなイメージで考えると分かりやすい。
--
--   city = CASE ... END
--
-- ここで city には、1行につき1つの値が入る。
-- したがって、その値の型が何であるかをDBMSが決定できなければならない。
--
-- もし戻り値候補がすべて文字列なら、
-- CASE 式全体は文字列型として扱いやすい。
--
-- もし戻り値候補がすべて数値なら、
-- CASE 式全体は数値型として扱いやすい。
--
-- しかし今回のように混在していると、
-- DBMSは暗黙変換を試みるか、エラーにするかを決める必要がある。
--
-- このため、
-- 「CASE の戻り値は同じデータ型にそろえる」
-- というのが基本原則になる。

-- ============================================
-- このSQLで起こりうる問題
-- ============================================
--
-- 1. DBMSによってはエラーになる
--    文字列と数値が混在しており、
--    CASE 式全体の型を決められない場合がある。
--
-- 2. DBMSによっては暗黙変換される
--    数値 100 が文字列 '100' に変換されるなど、
--    自動変換が行われることがある。
--
-- 3. 暗黙変換の結果が期待と異なる可能性がある
--    環境やDB製品によって挙動差があり、
--    他環境に移したときに同じ結果にならないことがある。
--
-- 4. 列の意味が崩れる
--    city という列名にもかかわらず数値が入るため、
--    利用側でデータ解釈が難しくなる。
--
-- 5. 後続処理で不具合を生みやすい
--    たとえば city に対して文字列関数をかける、
--    並べ替える、集計するなどの後続処理で
--    想定外の動作やエラーの原因になる。

-- ============================================
-- 正しい修正例の考え方
-- ============================================
--
-- もし city 列として都市名を返したいなら、
-- すべて文字列にそろえるべきである。
--
-- 例:
--
-- CASE
--     WHEN warehouse_id = 1 THEN 'New York'
--     WHEN warehouse_id = 2 THEN 'New Jersey'
--     WHEN warehouse_id = 3 THEN 'Los Angeles'
--     WHEN warehouse_id = 4 THEN 'Seattle'
--     WHEN warehouse_id = 5 THEN 'San Francisco'
--     ELSE NULL
-- END AS city
--
-- このように、すべての戻り値が文字列なら、
-- CASE 式全体も文字列型として自然に扱える。
--
-- 逆に、もし数値コードを返したいなら、
-- すべて数値にそろえるべきである。
--
-- 例:
--
-- CASE
--     WHEN warehouse_id = 1 THEN 100
--     WHEN warehouse_id = 2 THEN 200
--     WHEN warehouse_id = 3 THEN 300
--     WHEN warehouse_id = 4 THEN 400
--     WHEN warehouse_id = 5 THEN 500
--     ELSE NULL
-- END AS city_code
--
-- この場合は列名も city ではなく city_code のように、
-- 返す値の意味に合わせて付けるのが自然である。

-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. CASE 式の各分岐の戻り値型はそろえること
--    文字列列なのか数値列なのかを明確に設計する。
--
-- 2. 列名と返却値の意味を一致させること
--    city なら都市名文字列、
--    city_code なら数値コード、
--    というように意味をそろえる。
--
-- 3. 暗黙変換に依存しないこと
--    DBMSごとの差異や移植性の問題を避けるため、
--    型変換任せにしない設計が重要である。
--
-- 4. サンプルSQLでも型整合性を崩さないこと
--    学習用コードであっても、
--    「CASE は1つの型の値を返す式である」
--    という理解を崩さない形で書くことが大切である。
