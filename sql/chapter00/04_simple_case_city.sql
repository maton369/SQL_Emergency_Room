-- ============================================
-- ファイル名: 04_simple_case_city.sql
-- 目的:
--   Warehouse テーブルの warehouse_id をもとに、
--   対応する都市名 city を求めて表示する。
--
-- 概要:
--   このSQLでは「単純CASE式」を使っている。
--   単純CASE式は、ある1つの値を基準にして、
--   その値がどれに一致するかを順番に判定する書き方である。
--
--   書式の基本形は次の通りである。
--
--   CASE 比較対象の値
--       WHEN 値1 THEN 結果1
--       WHEN 値2 THEN 結果2
--       ...
--       ELSE 一致しない場合の結果
--   END
--
--   今回は warehouse_id の値を比較対象にして、
--   1, 2, 3, 4, 5 のどれに一致するかを調べ、
--   一致した場合に対応する都市名を返している。
-- ============================================

SELECT
    CASE warehouse_id
        -- ここでは「単純CASE式」を使っている。
        --
        -- 単純CASE式では、CASE の直後に書いた値
        -- （今回は warehouse_id）を基準として、
        -- 各 WHEN の値と「等しいかどうか」を比較する。
        --
        -- つまり、内部的には次のような意味になる。
        --
        -- CASE warehouse_id
        --     WHEN 1 THEN ...
        --
        -- は概念的には
        --
        -- CASE
        --     WHEN warehouse_id = 1 THEN ...
        --
        -- と同じ意味である。
        --
        -- そのため、等値比較を簡潔に書きたいときに
        -- 単純CASE式は非常に分かりやすい。

        WHEN 1 THEN 'New York'
        -- warehouse_id が 1 の行なら、
        -- city 列として 'New York' を返す。

        WHEN 2 THEN 'New Jersey'
        -- warehouse_id が 2 の行なら、
        -- city 列として 'New Jersey' を返す。

        WHEN 3 THEN 'Los Angels'
        -- warehouse_id が 3 の行なら、
        -- city 列として 'Los Angels' を返す。
        --
        -- 注意:
        -- 一般的な都市名表記としては
        -- 'Los Angeles' の可能性が高い。
        -- 学習用のサンプルであればこのままでもよいが、
        -- 実データとして扱う場合は表記の確認が必要である。

        WHEN 4 THEN 'Seattle'
        -- warehouse_id が 4 の行なら、
        -- city 列として 'Seattle' を返す。

        WHEN 5 THEN 'San Francisco'
        -- warehouse_id が 5 の行なら、
        -- city 列として 'San Francisco' を返す。

        ELSE NULL
        -- 1～5のどれにも一致しなかった場合の戻り値である。
        --
        -- たとえば warehouse_id = 6 や 10 など、
        -- 定義していない値が入っていた場合は NULL になる。
        --
        -- ELSE を省略した場合も、多くの場合
        -- 一致しなければ NULL が返るが、
        -- 今回は挙動を明示するために ELSE NULL と書いている。
        --
        -- 実務では NULL の代わりに
        -- 'Unknown' や 'Undefined' などの文字列を返すこともある。
    END AS city,
    -- CASE 式全体の結果に city という列名を付けている。
    -- そのため、SELECT結果ではこの計算結果が city 列として表示される。

    region
    -- 元の region 列もそのまま出力する。
    --
    -- つまり最終結果は、
    -- 「warehouse_id から計算した city」と
    -- 「もともとテーブルにある region」を
    -- 横に並べた形になる。

FROM Warehouse;
-- Warehouse テーブルを検索対象としている。
--
-- このSQLはテーブル内の各行に対して順に
-- warehouse_id を見て city を計算する。
-- ただし、SQLは集合指向言語であるため、
-- プログラムの for 文のように1行ずつ明示的に書くのではなく、
-- 「Warehouse の全行に対してこの式を適用する」
-- という形で記述している。

-- ============================================
-- 補足説明: このSQLのアルゴリズム
-- ============================================
--
-- このSQLがやっていることを1行単位で考えると、
-- 次のような流れになる。
--
-- 1. Warehouse テーブルから1行を取り出す
-- 2. その行の warehouse_id を確認する
-- 3. CASE 式で 1, 2, 3, 4, 5 のどれに一致するか調べる
-- 4. 一致した番号に対応する都市名を返す
-- 5. 一致しなければ NULL を返す
-- 6. city と region を結果として表示する
--
-- つまり本質的には、
-- 「warehouse_id という数値コードを、
--   人が読める都市名ラベルに変換する処理」
-- である。
--
-- 対応関係を表にすると次の通りである。
--
--   1 -> New York
--   2 -> New Jersey
--   3 -> Los Angels
--   4 -> Seattle
--   5 -> San Francisco
--   その他 -> NULL
--
-- ============================================
-- 単純CASE式と検索CASE式の違い
-- ============================================
--
-- 今回使っているのは単純CASE式であり、
-- 「1つの値が何に等しいか」を書くのに向いている。
--
-- 例:
--   CASE warehouse_id
--       WHEN 1 THEN 'New York'
--       WHEN 2 THEN 'New Jersey'
--   END
--
-- 一方で、より複雑な条件を書きたい場合は
-- 検索CASE式を使う。
--
-- 例:
--   CASE
--       WHEN warehouse_id BETWEEN 1 AND 2 THEN 'East'
--       WHEN warehouse_id >= 3 THEN 'West'
--       ELSE 'Other'
--   END
--
-- 単純CASE式:
--   等値比較を簡潔に書ける
--
-- 検索CASE式:
--   範囲条件や複数条件など柔軟な条件を書ける
--
-- 今回は warehouse_id の値と固定値を対応付けたいだけなので、
-- 単純CASE式が適している。
--
-- ============================================
-- 実務上の注意
-- ============================================
--
-- warehouse_id と都市名の対応が今後増えていく場合、
-- CASE 式が長くなり保守しづらくなる。
--
-- その場合は、都市対応表のようなマスタテーブルを別に作成し、
-- JOIN で結び付ける設計の方が拡張しやすい。
--
-- ただし、学習用・小規模な対応表・一時的な変換であれば、
-- CASE 式で直接書く方法は理解しやすく有効である。
