-- ============================================
-- ファイル名: 11_union_price_by_year_inefficient.sql
-- 目的:
--   年によって参照する価格列を切り替えて表示する。
--
-- 背景:
--   ItemPrice テーブルには
--     - price_tax_ex  … 税抜価格
--     - price_tax_in  … 税込価格
--   の2種類の価格が入っている。
--
--   今回の仕様は次の通りである。
--
--     - 2003年までは税抜価格を price として表示する
--     - 2004年以降は税込価格を price として表示する
--
--   その切り替えを UNION ALL を使って実現している。
--
-- 注意:
--   このSQLは「非効率な場合」の例として扱う。
--   理由は、同じ ItemPrice テーブルを
--   条件を変えて 2回 読んでいるからである。
--
--   本来は1回の表走査で済む内容なのに、
--   UNION ALL によって
--     - year <= 2003 のために1回
--     - year >= 2004 のために1回
--   と、同じテーブルを分けて読んでいる。
--
--   そのため、行数が大きくなると無駄が増える。
-- ============================================


-- ============================================
-- まずは実行計画を確認する
-- ============================================
-- MySQL では EXPLAIN を付けることで、
-- オプティマイザがこのSQLをどのように実行する予定かを確認できる。
--
-- このSQLでは UNION ALL を使っているため、
-- 実行計画上は「2つの SELECT が別々に実行される」形になりやすい。
--
-- つまり、ItemPrice テーブルに対して
-- 2本の問い合わせがぶら下がる構造になる。
--
-- データ量が小さいうちは問題が見えにくいが、
-- テーブルが大きくなると、
-- 同じ表を2回なめるコストが積み上がる。
--
-- 実行計画確認用:
EXPLAIN
SELECT item_name, year, price_tax_ex AS price
  FROM ItemPrice
 WHERE year <= 2003
UNION ALL
SELECT item_name, year, price_tax_in AS price
  FROM ItemPrice
 WHERE year >= 2004;


-- ============================================
-- 実データ取得用SQL
-- ============================================
SELECT item_name, year, price_tax_ex AS price
  FROM ItemPrice
 WHERE year <= 2003
-- 1本目の SELECT である。
--
-- ここでは 2003年以下の行だけを対象にしている。
--
-- 条件:
--   year <= 2003
--
-- したがって、対象になるのは
--   2002年
--   2003年
-- のデータである。
--
-- 出力する列は次の3つである。
--
--   item_name
--     商品名
--
--   year
--     対象年
--
--   price_tax_ex AS price
--     税抜価格を price という名前で出力する
--
-- ここで AS price を使っている理由は、
-- 1本目と2本目の SELECT で元の列名が異なるためである。
--
--   1本目では price_tax_ex
--   2本目では price_tax_in
--
-- を使うが、UNION ALL で縦に連結するためには
-- 「同じ意味の列」として扱いたい。
--
-- そこで両方とも price という同じ列名にそろえている。

UNION ALL
-- UNION ALL は、1本目と2本目の SELECT 結果を
-- そのまま縦に結合する。
--
-- ここで UNION ではなく UNION ALL を使っている点が重要である。
--
-- UNION:
--   重複行を除去する
--
-- UNION ALL:
--   重複行を除去せず、そのまま連結する
--
-- 今回は
--   year <= 2003
-- と
--   year >= 2004
-- で条件が重ならないため、
-- 重複除去は不要である。
--
-- したがって UNION より UNION ALL の方が自然であり、
-- 不要な重複排除コストもかからない。
--
-- ただし、それでもなお
-- 「テーブルを2回読む」という点では非効率である。

SELECT item_name, year, price_tax_in AS price
  FROM ItemPrice
 WHERE year >= 2004;
-- 2本目の SELECT である。
--
-- ここでは 2004年以上の行だけを対象にしている。
--
-- 条件:
--   year >= 2004
--
-- したがって、対象になるのは
--   2004年
--   2005年
-- のデータである。
--
-- 出力する列は
--   item_name
--   year
--   price_tax_in AS price
-- である。
--
-- この部分では税込価格を使っているため、
-- 2004年以降だけ税込価格へ切り替える、という仕様を表現している。
--
-- 結果として、1本目と2本目を合わせると
-- 「年によって price の意味が変わる結果セット」
-- を得られる。


-- ============================================
-- このSQLのアルゴリズム
-- ============================================
--
-- このSQLは、全体として次のアルゴリズムで動いている。
--
-- 1. ItemPrice テーブルから 2003年以下の行を取り出す
-- 2. その行では price_tax_ex を price として返す
-- 3. ItemPrice テーブルから 2004年以上の行を取り出す
-- 4. その行では price_tax_in を price として返す
-- 5. 2つの結果集合を UNION ALL で縦に連結する
--
-- つまり、発想としては
--
--   「昔の年のデータ群」
--   「新しい年のデータ群」
--
-- を別々に作って最後にくっつけている。
--
-- 図にすると次のようなイメージである。
--
--   ItemPrice
--      |
--      +--> year <= 2003 を抽出 --> price_tax_ex を採用 --+
--      |                                                   |
--      +--> year >= 2004 を抽出 --> price_tax_in を採用 --+--> UNION ALL
--
-- これは仕様表現としては分かりやすいが、
-- 同じ入力表を分岐ごとに再読込している点が非効率である。


-- ============================================
-- なぜ非効率なのか
-- ============================================
--
-- 非効率な理由は、
-- 1つのテーブル ItemPrice を 2回 読んでいるからである。
--
-- 本来、この問題は各行について
--
--   if year <= 2003:
--       税抜価格を使う
--   else:
--       税込価格を使う
--
-- という「行ごとの条件分岐」で済む。
--
-- つまり、1回の表走査の中で CASE 式を使えば解ける。
--
-- しかし UNION ALL 版では、
--
--   SELECT ... FROM ItemPrice WHERE year <= 2003
--   SELECT ... FROM ItemPrice WHERE year >= 2004
--
-- の2本に分かれているため、
-- DBMSは原則として
-- 「前半用に1回」
-- 「後半用に1回」
-- 読みに行く必要がある。
--
-- データ件数が小さいと差は小さいが、
-- 大きなテーブルでは次のような不利が出る。
--
-- 1. 表アクセス回数が増える
-- 2. インデックスやページ読み込みが重複する
-- 3. CPU・I/O の無駄が増える
-- 4. SQLが冗長になり保守性も落ちる
--
-- 特に今回のように、
-- 「各行に対してどちらの列を使うかを切り替えるだけ」
-- の問題では、UNION ALL は回りくどい。


-- ============================================
-- 実行計画で何を見ればよいか
-- ============================================
--
-- EXPLAIN の結果では、環境によって表示形式は多少異なるが、
-- 基本的には次の点を見る。
--
-- 1. ItemPrice が何回出てくるか
--    UNION ALL を使っているので、
--    実行計画上も ItemPrice へのアクセスが 2 系統に分かれやすい。
--
-- 2. access type
--    ALL, range, index などが表示される。
--    year 列にインデックスがなければ ALL
--    つまり全表走査になる可能性が高い。
--
-- 3. rows
--    推定走査行数を見る。
--    2つの SELECT がそれぞれ何行読む想定かを確認する。
--
-- 4. Extra
--    Using where などが表示されることがある。
--    これは取得後に WHERE 条件で絞っていることを示す。
--
-- 今回、year に単独インデックスが無い場合、
-- 複合主キー (item_id, year) は存在していても
-- year 単独条件では効きにくいため、
-- かなりの環境で全表走査寄りになりやすい。
--
-- その結果、
--   全表走査を2回
-- のような形になる可能性があり、
-- 「非効率な例」として分かりやすい。


-- ============================================
-- このSQLが返す結果の意味
-- ============================================
--
-- 結果の列は
--
--   item_name
--   year
--   price
--
-- の3つである。
--
-- ただし price 列は年によって意味が異なる。
--
--   2003年以下 -> 税抜価格
--   2004年以上 -> 税込価格
--
-- したがって、price という1本の列に見えても、
-- 内部的には
--   一部の行は price_tax_ex
--   一部の行は price_tax_in
-- を採用した混合列である。
--
-- この「年によって採用列が変わる」という仕様自体は、
-- CASE 式で表現する方が自然である。


-- ============================================
-- より自然で効率のよい書き方の方向性
-- ============================================
--
-- この問題は、本来は1回の SELECT の中で
-- CASE 式を使って書くのが自然である。
--
-- 例:
--
-- SELECT
--     item_name,
--     year,
--     CASE
--         WHEN year <= 2003 THEN price_tax_ex
--         ELSE price_tax_in
--     END AS price
-- FROM ItemPrice;
--
-- この書き方なら、
-- ItemPrice を1回読むだけで済む。
--
-- つまりアルゴリズムは
--
--   各行を1回見る
--   -> 年を判定する
--   -> 使う価格列を選ぶ
--
-- という、より素直な形になる。
--
-- 今回の UNION ALL 版は、
-- この1回の分岐処理を
-- 「2本の別クエリ + 結合」
-- に分解してしまっているため、
-- 非効率な例として扱われる。


-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. UNION ALL は「結果集合を分けて作る」発想であり、
--    行ごとの単純な条件切り替えには過剰なことがある。
--
-- 2. 同じテーブルを複数回読む構造は、
--    データ量が増えるとコスト差が目立つ。
--
-- 3. 実行計画では、テーブル参照回数と access type を確認すること。
--
-- 4. 複合主キー (item_id, year) があっても、
--    year 単独条件では期待通りに効かないことがある。
--
-- 5. 「分岐の条件が行ごとに完結している」場合は、
--    UNION より CASE をまず検討するのが基本である。
