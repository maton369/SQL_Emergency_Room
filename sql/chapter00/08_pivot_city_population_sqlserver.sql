-- ============================================
-- ファイル名: 08_pivot_city_population_sqlserver.sql
-- 目的:
--   City テーブルに入っている都市ごとの人口データを、
--   SQL Server の PIVOT を使って横持ち形式に変換する。
--
-- テーマ:
--   PIVOT は「行に並んでいるカテゴリ値を列へ変換する」ための構文である。
--   今回は city 列の値
--
--     'New York'
--     'Los Angels'
--     'San Francisco'
--     'New Orleans'
--
--   を列名へ変換し、その各列に population の合計値を配置している。
-- ============================================

SELECT
    [New York],
    [Los Angels],
    [San Francisco],
    [New Orleans]
    -- 最終的に欲しい出力列を明示している。
    --
    -- SQL Server では、列名に空白が含まれる場合、
    -- [ ] で囲って識別子として扱う。
    --
    -- たとえば New York は空白を含むため、
    -- そのまま書くのではなく [New York] と書く必要がある。
    --
    -- ここで指定している4列が、
    -- PIVOT によって作られる横持ち後の列になる。

FROM
(
    SELECT city, population
    FROM City
    -- ここは PIVOT に渡す元データを作る部分である。
    --
    -- まず City テーブルから
    --   city
    --   population
    -- の2列だけを取り出している。
    --
    -- つまり、PIVOT の入力として
    -- 「都市名」と「人口」のペアを準備している。
    --
    -- この部分はサブクエリであり、
    -- 後続の PIVOT にとっての元表となる。
) AS SourceTable
-- サブクエリに SourceTable という別名を付けている。
--
-- SQL Server の PIVOT 構文では、
-- 元になる表またはサブクエリに別名が必要である。

PIVOT
(
    SUM(population)
    -- PIVOT では、変換後の各列に入れる値を
    -- 集約関数で指定する必要がある。
    --
    -- 今回は SUM(population) を指定しているため、
    -- 同じ city に対応する行が複数あれば、
    -- その人口を合計する。
    --
    -- 今回のサンプルデータでは city は主キーで重複しないため、
    -- 実質的には各都市の population がそのまま入る。
    --
    -- ただし、PIVOT 構文上は「集約」が必須なので、
    -- SUM を使っている。

    FOR city IN ([New York], [Los Angels], [San Francisco], [New Orleans])
    -- FOR city は、
    -- 「city 列の値を列方向へ展開する」
    -- ことを意味する。
    --
    -- IN (...) の中には、
    -- 横持ち後に列として作成したい city の値を列挙する。
    --
    -- つまり今回の意味は、
    --
    --   city = 'New York'        の行は [New York] 列へ
    --   city = 'Los Angels'      の行は [Los Angels] 列へ
    --   city = 'San Francisco'   の行は [San Francisco] 列へ
    --   city = 'New Orleans'     の行は [New Orleans] 列へ
    --
    -- population を配置する、ということである。
    --
    -- 重要なのは、
    -- PIVOT は「指定した値だけ」を列化する点である。
    -- もし City テーブルに別の都市が入っていても、
    -- IN (...) に書かなければ結果列には現れない。
) AS PivotTable;
-- PIVOT の結果にも PivotTable という別名を付けている。
--
-- これにより、PIVOT 後の結果を1つの表として扱っている。

-- ============================================
-- このPIVOT処理のアルゴリズム
-- ============================================
--
-- このSQLのアルゴリズムを段階的に見ると次の通りである。
--
-- 1. City テーブルから city と population を取り出す
--
--    入力データは次のような縦持ち形式である。
--
--      city            | population
--      ----------------+-----------
--      New York        | 8460000
--      Los Angels      | 3840000
--      San Francisco   | 815000
--      New Orleans     | 377000
--
-- 2. city 列の値をカテゴリとして扱う
--
--    ここでのカテゴリは
--      New York
--      Los Angels
--      San Francisco
--      New Orleans
--    の4種類である。
--
-- 3. 各カテゴリを列名に変換する
--
--    つまり、行方向に並んでいた都市名を
--    横方向の列へ変換する。
--
-- 4. 各列に対して SUM(population) の結果を置く
--
--    city = 'New York' の行の population は [New York] 列へ、
--    city = 'Los Angels' の行の population は [Los Angels] 列へ、
--    という形で値が配置される。
--
-- 5. 最終的に1行の横持ち結果を返す
--
--    出力イメージは次の通りである。
--
--      New York | Los Angels | San Francisco | New Orleans
--      ---------+------------+---------------+------------
--      8460000  | 3840000    | 815000        | 377000
--
-- つまり、このSQLの本質は
-- 「city 列のカテゴリ値を列見出しへ回転し、
--   population の値を対応する列へ配置する」
-- ことである。

-- ============================================
-- なぜ SUM を使うのか
-- ============================================
--
-- 今回は city が主キーなので、
-- 1都市につき1行しか存在しない。
-- そのため、直感的には集約は不要に見える。
--
-- しかし、PIVOT 構文では集約関数を指定する必要がある。
--
-- もし同じ都市が複数行あった場合、
-- SUM(population) はそれらを合計した値を返す。
--
-- たとえば次のようなデータがあれば、
--
--   city       | population
--   -----------+-----------
--   New York   | 100
--   New York   | 200
--
-- PIVOT 後の [New York] 列には 300 が入る。
--
-- 今回は1都市1行なので、
-- SUM(population) の結果は元の population と同じになる。

-- ============================================
-- PIVOT を使わない場合との違い
-- ============================================
--
-- 同じ結果は CASE 式と集約関数でも作れる。
-- たとえば概念的には次のような考え方である。
--
--   SUM(CASE WHEN city = 'New York' THEN population END) AS [New York]
--
-- これを各都市について書けば同様の横持ち結果を得られる。
--
-- ただし SQL Server では、PIVOT を使うことで
-- 「行を列へ変換する意図」をより明確に表現できる。
--
-- 一方で、PIVOT はDB製品依存があるため、
-- 移植性を重視する場合は CASE + 集約の方が有利なこともある。

-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. PIVOT する列値は固定列挙である
--    IN (...) に明示した都市しか列にならない。
--    新しい都市が増えた場合はSQLを書き換える必要がある。
--
-- 2. 列名に空白がある場合は [ ] が必要である
--    SQL Server では [New York] のように書く。
--
-- 3. city 名の表記ゆれに注意する
--    'Los Angels' と 'Los Angeles' が混在すると、
--    別カテゴリとして扱われてしまう。
--    PIVOT は文字列一致に基づくため、
--    表記の統一が非常に重要である。
--
-- 4. 主キー設計により集約結果の意味が変わる
--    今回は city が主キーなので1都市1行だが、
--    主キーでなければ SUM の結果は「合計人口」になる。
--
-- 5. CHAR 型は末尾空白に注意が必要である
--    CHAR(32) は固定長のため、環境や比較条件によっては
--    末尾空白の扱いを意識する必要がある。
--    実務では VARCHAR の方が自然な場面も多い。
