-- ============================================
-- ファイル名: 09_pivot_city_population_case_mysql.sql
-- 目的:
--   City テーブルに格納されている都市ごとの人口データを、
--   CASE式と集約関数 SUM を使って横持ち形式に変換する。
--
-- 背景:
--   SQL Server には PIVOT 構文があるが、
--   MySQL では同じ形の PIVOT 構文は使えない。
--
--   そのため、MySQL では
--
--     SUM(CASE WHEN 条件 THEN 値 ELSE 0 END)
--
--   という形を使って、疑似的にピボットを実現することが多い。
--
-- このSQLの本質:
--   もともと City テーブルは
--   「1行に1都市」という縦持ちデータである。
--
--   例:
--     city            | population
--     ----------------+-----------
--     New York        | 8460000
--     Los Angels      | 3840000
--     San Francisco   | 815000
--     New Orleans     | 377000
--
--   これを次のような横持ち形式に変換したい。
--
--     New York | Los Angels | San Francisco | New Orleans
--     ---------+------------+---------------+------------
--     8460000  | 3840000    | 815000        | 377000
--
--   そのために、
--   各都市ごとに「その都市なら population を返し、
--   それ以外なら 0 を返す CASE式」を作り、
--   最後に SUM で足し合わせて1列にまとめている。
-- ============================================

SELECT
    SUM(
        CASE
            WHEN city = 'New York' THEN population
            ELSE 0
        END
    ) AS "New York",
    -- New York 列を作る処理である。
    --
    -- まず CASE 式で各行を判定する。
    --
    --   city = 'New York' の行
    --       -> その行の population を返す
    --
    --   それ以外の都市の行
    --       -> 0 を返す
    --
    -- 例えば City テーブルが次の4行なら、
    --
    --   New York        | 8460000
    --   Los Angels      | 3840000
    --   San Francisco   | 815000
    --   New Orleans     | 377000
    --
    -- CASE 式の結果は概念的に
    --
    --   8460000
    --   0
    --   0
    --   0
    --
    -- となる。
    --
    -- その後 SUM で全部足すので、
    --
    --   8460000 + 0 + 0 + 0 = 8460000
    --
    -- となり、最終的に "New York" 列の値になる。
    --
    -- このように、
    -- 「特定の都市の行だけ値を残し、他は0にする」
    -- ことで、都市ごとの人口を横持ち列として取り出している。

    SUM(
        CASE
            WHEN city = 'Los Angels' THEN population
            ELSE 0
        END
    ) AS "Los Angels",
    -- Los Angels 列を作る処理である。
    --
    -- 考え方は New York 列と同じで、
    -- city が 'Los Angels' のときだけ population を残し、
    -- それ以外は 0 にする。
    --
    -- 例:
    --
    --   city            | population | CASE結果
    --   ----------------+------------+---------
    --   New York        | 8460000    | 0
    --   Los Angels      | 3840000    | 3840000
    --   San Francisco   | 815000     | 0
    --   New Orleans     | 377000     | 0
    --
    -- これを SUM すると 3840000 になり、
    -- "Los Angels" 列に人口が入る。
    --
    -- 注意:
    -- 一般的には 'Los Angeles' の表記が多いが、
    -- ここではテーブルに入っている文字列と
    -- 完全一致させる必要がある。
    --
    -- CASE式の判定は文字列一致なので、
    -- テーブル側が 'Los Angels' なら、
    -- SQL側も 'Los Angels' と書かなければ一致しない。

    SUM(
        CASE
            WHEN city = 'San Francisco' THEN population
            ELSE 0
        END
    ) AS "San Francisco",
    -- San Francisco 列を作る処理である。
    --
    -- city が 'San Francisco' の行だけ population を返し、
    -- 他都市の行では 0 を返す。
    --
    -- その結果、SUM すると
    -- San Francisco の人口だけが残る。
    --
    -- この処理を各都市について1本ずつ書くことで、
    -- 本来は行方向に並んでいたカテゴリ値を、
    -- 列方向へ並べ替えることができる。

    SUM(
        CASE
            WHEN city = 'New Orleans' THEN population
            ELSE 0
        END
    ) AS "New Orleans"
    -- New Orleans 列を作る処理である。
    --
    -- ここでも同様に、
    -- New Orleans の行だけ population を返し、
    -- 他の行は 0 にする。
    --
    -- これにより、4つの都市それぞれについて
    -- 1列ずつ人口を取り出せる。
    --
    -- つまり、この SELECT 文全体では
    -- 「都市ごとの population を個別の列に分解している」
    -- ことになる。

FROM City;
-- City テーブルを検索対象にしている。
--
-- City テーブルは縦持ちの元データであり、
-- このテーブルの全行に対して各 CASE 式が評価される。
--
-- 各 CASE 式は全行を見て、
-- 自分が担当する都市の行だけ値を残し、
-- 他は 0 にする。
--
-- その後 SUM で集約することで、
-- 都市ごとに1つの値へまとめている。

-- ============================================
-- このSQLのアルゴリズム
-- ============================================
--
-- 全体の流れを1段ずつ分解すると次の通りである。
--
-- 1. City テーブルから全行を読む
--
-- 2. 各都市専用の CASE 式を用意する
--    - New York 用
--    - Los Angels 用
--    - San Francisco 用
--    - New Orleans 用
--
-- 3. 各 CASE 式は、自分に対応する都市の行なら population を返し、
--    それ以外の行なら 0 を返す
--
-- 4. SUM を使って各 CASE 式の結果を合計する
--
-- 5. 合計結果を、それぞれの都市名の列として出力する
--
-- つまり、アルゴリズムの本質は
--
--   「条件に一致する行だけ値を通し、
--     一致しない行を0にしてから合計する」
--
-- ことである。
--
-- この考え方により、
-- 本来は行に入っていた city のカテゴリを
-- 列へ変換できる。
--
-- これは CASE式を使ったピボットの代表的な実装方法である。

-- ============================================
-- イメージ図
-- ============================================
--
-- 元データ:
--
--   city            | population
--   ----------------+-----------
--   New York        | 8460000
--   Los Angels      | 3840000
--   San Francisco   | 815000
--   New Orleans     | 377000
--
-- New York列を作る CASE:
--
--   CASE WHEN city = 'New York' THEN population ELSE 0 END
--
-- 結果:
--
--   8460000
--   0
--   0
--   0
--
-- SUM:
--
--   8460000
--
-- Los Angels列を作る CASE:
--
--   CASE WHEN city = 'Los Angels' THEN population ELSE 0 END
--
-- 結果:
--
--   0
--   3840000
--   0
--   0
--
-- SUM:
--
--   3840000
--
-- 同じことを各都市について行うと、
-- 最終的に横持ち結果になる。
--
--   New York | Los Angels | San Francisco | New Orleans
--   ---------+------------+---------------+------------
--   8460000  | 3840000    | 815000        | 377000

-- ============================================
-- なぜ ELSE 0 が必要なのか
-- ============================================
--
-- ELSE 0 を書いている理由は、
-- 対象外の都市の行を「合計に影響しない値」にするためである。
--
-- もし ELSE を書かずに NULL のままにすると、
-- DBMS の集約関数の扱いに依存する部分が出てきて、
-- 学習段階では理解しづらくなることがある。
--
-- ELSE 0 にしておけば、
-- 「一致しない行は人口ゼロとして扱う」
-- という意味が明確になる。
--
-- そのため、CASE式ピボットでは
-- ELSE 0 は非常に分かりやすい書き方である。

-- ============================================
-- なぜ SUM を使うのか
-- ============================================
--
-- CASE 式だけでは、各行ごとに
-- population または 0 が返るだけである。
--
-- そのままでは複数行のまま残るため、
-- 1つの都市について1つの値にまとめる必要がある。
--
-- そこで SUM を使う。
--
-- 例えば New York 列では
--
--   8460000
--   0
--   0
--   0
--
-- を足し合わせることで、
--
--   8460000
--
-- という1つの値に集約できる。
--
-- つまり SUM は、
-- 「条件で抽出した値を1つのセルへ圧縮する」
-- 役割を持っている。

-- ============================================
-- このSQLが成り立つ前提
-- ============================================
--
-- このSQLでは city ごとに1行しかない前提なので、
-- SUM の結果はその都市の population そのものになる。
--
-- もし同じ都市が複数行ある場合は、
-- その都市の population が合計される。
--
-- 例:
--
--   city       | population
--   -----------+-----------
--   New York   | 100
--   New York   | 200
--
-- この場合、
--
--   SUM(CASE WHEN city = 'New York' THEN population ELSE 0 END)
--
-- の結果は 300 になる。
--
-- したがって、このSQLは
-- 「都市ごとに1行」でも
-- 「都市ごとに複数行」でも使えるが、
-- 後者では意味が「人口そのもの」ではなく
-- 「人口の合計」になる点に注意が必要である。

-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. 列名を増やしたい場合は CASE 式を追加する必要がある
--    新しい都市が増えても、自動で列は増えない。
--    そのため、この方法は静的ピボットである。
--
-- 2. city の表記ゆれに注意すること
--    'Los Angels' と 'Los Angeles' が混在すると、
--    別カテゴリとして扱われる。
--    CASE式は完全一致で判定するため、
--    表記統一が重要である。
--
-- 3. 別のDBでも比較的移植しやすい
--    PIVOT 構文はDB依存があるが、
--    CASE + SUM は多くのDBで使える。
--    そのため移植性の高いピボット表現として有用である。
--
-- 4. 都市数が多いとSQLが長くなる
--    CASE式を列ごとに1本書く必要があるため、
--    カテゴリ数が増えると保守しにくくなる。
--
-- 5. 列エイリアスの書き方はDBにより差がある
--    MySQL では通常、識別子として扱いたい場合は
--    "..." より `...` の方が分かりやすい場合がある。
--    ただし、このサンプルでは教材の記法に合わせている。
