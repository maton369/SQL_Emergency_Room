-- ============================================
-- ファイル名: 10_create_item_price.sql
-- 目的:
--   商品ごとの年別価格を管理する ItemPrice テーブルを作成し、
--   サンプルデータを登録する。
--
-- 概要:
--   このテーブルは、
--   「どの商品が、どの年に、いくらで売られていたか」
--   を管理するための価格履歴テーブルである。
--
--   1行は
--   「ある商品(item_id)の、ある年(year)における価格情報」
--   を表している。
--
--   したがって、このテーブルは単なる商品マスタではなく、
--   時系列を持つ価格履歴データである点が重要である。
--
-- 例:
--   item_id = '100' のカップは
--   2002年, 2003年, 2004年, 2005年 に
--   それぞれ異なる価格で登録されている。
--
--   このように、同じ商品でも年が異なれば別行として保持する。
-- ============================================

CREATE TABLE ItemPrice
(
    item_id CHAR(3) NOT NULL,
    -- item_id は商品IDである。
    --
    -- CHAR(3) は固定長3文字の文字列型である。
    -- ここでは '100', '101', '102' のような
    -- 3桁の商品コードを保存する想定で使っている。
    --
    -- 数値のように見えるが、実際には文字列として扱っている。
    -- そのため 100 ではなく '100' のようにクォート付きで登録する。
    --
    -- 商品コードは先頭ゼロを含むこともあるため、
    -- 実務ではこのように文字列で管理する設計はよくある。
    --
    -- NOT NULL により、商品IDが未設定の行は許可しない。

    year INTEGER NOT NULL,
    -- year は価格が適用される年を表す。
    --
    -- ここでは 2002, 2003, 2004, 2005 のような西暦年を整数で管理している。
    --
    -- NOT NULL により、年が不明な価格データは登録できない。
    --
    -- この列があることで、
    -- 同じ商品について複数年の価格変化を追跡できる。

    item_name VARCHAR(32) NOT NULL,
    -- item_name は商品の名称である。
    --
    -- VARCHAR(32) は可変長文字列型であり、
    -- 商品名の長さに応じて必要な分だけ領域を使う。
    --
    -- 商品名は通常、長さが固定ではないため、
    -- CHAR より VARCHAR の方が自然な設計である。
    --
    -- ここでは
    --   カップ
    --   スプーン
    --   ナイフ
    -- などが入る。
    --
    -- NOT NULL により、商品名が空の価格データは許可しない。
    --
    -- 注意:
    -- item_id から商品名が一意に決まるのであれば、
    -- 正規化の観点では item_name を別の商品マスタへ分離する設計もありうる。
    -- ただし学習用としては、1つのテーブルにまとまっている方が分かりやすい。

    price_tax_ex INTEGER NOT NULL,
    -- price_tax_ex は税抜価格である。
    --
    -- "tax_ex" は tax exclusive の略と考えると理解しやすく、
    -- 税を含まない本体価格を表している。
    --
    -- たとえば 500, 520, 600 などの整数値が入る。
    --
    -- 金額を整数で管理しているため、
    -- 小数点を含まない通貨単位を前提にしている。
    -- 日本円のように通常は整数で扱う通貨では自然な設計である。

    price_tax_in INTEGER NOT NULL,
    -- price_tax_in は税込価格である。
    --
    -- "tax_in" は tax inclusive の略と考えると理解しやすく、
    -- 消費税を含んだ販売価格を表している。
    --
    -- たとえば税抜500円に対して税込525円のように、
    -- 税込み後の価格を保持する。
    --
    -- この列を別に持つことで、
    -- 税率や端数処理の結果をあらかじめ確定値として保存できる。
    --
    -- 一方で、税抜価格から計算可能なら冗長にも見える。
    -- ただし、時代ごとの税率や丸め規則を厳密に保持したい場合、
    -- 実務では税込価格を別列で保存する意義がある。

    CONSTRAINT pk_ItemPrice PRIMARY KEY (item_id, year)
    -- 主キーを (item_id, year) の複合キーで定義している。
    --
    -- これはこのテーブルの設計上、非常に重要である。
    --
    -- 意味としては、
    --   「同じ商品について、同じ年の価格情報は1行しか持てない」
    -- という制約を表している。
    --
    -- たとえば
    --   ('100', 2002)
    -- は1回しか登録できない。
    --
    -- しかし
    --   ('100', 2002)
    -- と
    --   ('100', 2003)
    -- は year が異なるため共存できる。
    --
    -- つまりこの主キーは、
    -- 「商品 × 年」で価格履歴を一意に識別する
    -- というテーブル設計を実現している。
);

-- ============================================
-- サンプルデータ登録
-- ============================================
-- 以下では、3商品について2002年から2005年までの価格を登録する。
--
-- 商品ごとの価格推移を見ると、
-- 値上がりした商品、価格が変わらない商品、
-- 値下がりした商品が含まれている。
--
-- そのため、このデータは
--   年ごとの価格変化
--   値上げ・値下げの判定
--   前年比較
--   横持ち変換
-- などのSQL練習に向いている。
-- ============================================

INSERT INTO ItemPrice VALUES ('100', 2002, 'カップ',   500, 525);
-- 商品ID 100 のカップについて、2002年の価格を登録する。
-- 税抜価格は 500、税込価格は 525 である。

INSERT INTO ItemPrice VALUES ('100', 2003, 'カップ',   520, 546);
-- 商品ID 100 のカップについて、2003年の価格を登録する。
-- 2002年の税抜 500 から 520 に上がっている。
--
-- このように、同じ商品でも年が違えば別行として記録される。
-- これが履歴テーブルの基本的な考え方である。

INSERT INTO ItemPrice VALUES ('100', 2004, 'カップ',   600, 630);
-- カップの 2004年価格である。
-- さらに値上がりしており、
-- 2002 -> 2003 -> 2004 と価格が上昇していることが分かる。

INSERT INTO ItemPrice VALUES ('100', 2005, 'カップ',   600, 630);
-- カップの 2005年価格である。
-- 2004年と同じ価格なので、この年は価格据え置きである。
--
-- このようなデータが入っていると、
-- 前年比で「上がった / 下がった / 変わらない」を判定するSQLの練習ができる。

INSERT INTO ItemPrice VALUES ('101', 2002, 'スプーン', 500, 525);
-- 商品ID 101 のスプーンについて、2002年の価格を登録する。

INSERT INTO ItemPrice VALUES ('101', 2003, 'スプーン', 500, 525);
-- スプーンの 2003年価格である。
-- 前年と同じ価格であり、価格変動はない。

INSERT INTO ItemPrice VALUES ('101', 2004, 'スプーン', 500, 525);
-- スプーンの 2004年価格である。
-- 引き続き価格は変わっていない。

INSERT INTO ItemPrice VALUES ('101', 2005, 'スプーン', 500, 525);
-- スプーンの 2005年価格である。
-- 2002年から2005年まで、税抜・税込ともにずっと同じ価格である。
--
-- この商品は「価格変化なし」の例として使える。

INSERT INTO ItemPrice VALUES ('102', 2002, 'ナイフ',   600, 630);
-- 商品ID 102 のナイフについて、2002年の価格を登録する。

INSERT INTO ItemPrice VALUES ('102', 2003, 'ナイフ',   550, 577);
-- ナイフの 2003年価格である。
-- 2002年の税抜 600 から 550 に下がっている。
--
-- つまり、この商品は値下がりの例である。

INSERT INTO ItemPrice VALUES ('102', 2004, 'ナイフ',   550, 577);
-- ナイフの 2004年価格である。
-- 2003年と同じなので、ここでは価格据え置きである。

INSERT INTO ItemPrice VALUES ('102', 2005, 'ナイフ',   400, 420);
-- ナイフの 2005年価格である。
-- さらに値下がりしており、2002年から見るとかなり価格が下がっている。
--
-- このように、ナイフは
--   値下がり -> 据え置き -> 値下がり
-- という推移を持っている。

-- ============================================
-- このテーブルのデータ構造
-- ============================================
--
-- データを表でイメージすると次のようになる。
--
--   item_id | year | item_name | price_tax_ex | price_tax_in
--   --------+------+-----------+--------------+-------------
--   100     | 2002 | カップ    | 500          | 525
--   100     | 2003 | カップ    | 520          | 546
--   100     | 2004 | カップ    | 600          | 630
--   100     | 2005 | カップ    | 600          | 630
--   101     | 2002 | スプーン  | 500          | 525
--   101     | 2003 | スプーン  | 500          | 525
--   101     | 2004 | スプーン  | 500          | 525
--   101     | 2005 | スプーン  | 500          | 525
--   102     | 2002 | ナイフ    | 600          | 630
--   102     | 2003 | ナイフ    | 550          | 577
--   102     | 2004 | ナイフ    | 550          | 577
--   102     | 2005 | ナイフ    | 400          | 420
--
-- 行の意味は
--   「ある商品の、ある年の価格」
-- であり、
-- 列の意味は
--   「商品識別子」「年」「商品名」「税抜価格」「税込価格」
-- である。
--
-- このような構造は、時系列付きのマスタ履歴や価格履歴としてよく使われる。

-- ============================================
-- このデータのアルゴリズム的な見方
-- ============================================
--
-- このテーブルは、単なる一覧表ではなく、
-- SQLで次のような分析を行う前提データとして見ると理解しやすい。
--
-- 1. 商品ごとの価格推移を見る
--    例:
--      カップは 500 -> 520 -> 600 -> 600
--
-- 2. 前年と比較して値上がり・値下がりを判定する
--    例:
--      ナイフは 600 -> 550 なので値下がり
--
-- 3. 商品ごとに年を横持ちへ変換する
--    例:
--      2002, 2003, 2004, 2005 を列として並べる
--
-- 4. 税抜と税込の差や税率相当を確認する
--    例:
--      500 -> 525 なので 25円分上乗せされている
--
-- 5. 一定期間で価格が変わっていない商品を探す
--    例:
--      スプーンは全期間で同じ価格
--
-- つまり、このデータは
-- 「時間軸を含む比較・集約・ピボット・変化検知」
-- の練習に向いた構造になっている。

-- ============================================
-- 商品ごとの特徴
-- ============================================
--
-- 1. カップ (item_id = '100')
--    税抜価格:
--      500 -> 520 -> 600 -> 600
--    値上がりし、その後据え置きになっている。
--
-- 2. スプーン (item_id = '101')
--    税抜価格:
--      500 -> 500 -> 500 -> 500
--    全期間で価格変化がない。
--
-- 3. ナイフ (item_id = '102')
--    税抜価格:
--      600 -> 550 -> 550 -> 400
--    値下がりし、その後据え置き、さらに再度値下がりしている。
--
-- このように、異なる価格変動パターンを持つ商品が含まれているため、
-- 比較系SQLの教材としてバランスがよい。

-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. item_name は商品マスタへ分離できる可能性がある
--    item_id ごとに item_name が固定なら、
--    正規化の観点では別テーブルに分けられる。
--
-- 2. year は年度なのか暦年なのかを明確にする必要がある
--    実務では 2002年度 と 2002年 が異なる場合がある。
--
-- 3. 税込価格を保持するか計算するかは設計判断である
--    税率変更や丸め誤差を厳密に保持したいなら保存が有効である。
--
-- 4. CHAR(3) の商品IDはコード体系が固定長である前提である
--    将来桁数が増える可能性があるなら見直しが必要である。
--
-- 5. 複合主キーにより履歴の一意性を保証している
--    同一商品・同一年の重複登録を防ぐ点で重要な設計である。
