-- ============================================
-- ファイル名: 05_case_short_circuit_city.sql
-- 目的:
--   Warehouse テーブルの warehouse_id を条件分岐し、
--   対応する都市名 city を求めて表示する。
--
-- テーマ:
--   このSQLは「CASE式は上から順に評価され、最初に真になった条件で確定する」
--   という性質を確認するための例である。
--
--   これを一般に、CASE式の短絡評価
--   （厳密には「最初に一致した条件で打ち切られる性質」）
--   として説明することが多い。
--
-- ポイント:
--   最初の WHEN で
--
--       warehouse_id IN (1, 2)
--
--   と書いているため、
--   warehouse_id = 2 の行はそこで確定してしまう。
--
--   その結果、次の
--
--       WHEN warehouse_id = 2 THEN 'New Jersey'
--
--   は実際には到達しない条件になる。
--
--   つまり、warehouse_id = 2 の行に対しては
--   'New Jersey' ではなく 'New York' が返る。
-- ============================================

SELECT
    CASE
        -- ここから CASE 式による条件分岐を行う。
        --
        -- この形式は「検索CASE式」と呼ばれる。
        -- 単純CASE式のように 1つの値を固定して比較するのではなく、
        -- 各 WHEN に自由な条件式を書けるのが特徴である。
        --
        -- そのため、
        --   = 比較
        --   IN
        --   BETWEEN
        --   AND / OR
        -- などを柔軟に使える。
        --
        -- また、CASE 式は上から順に条件を評価し、
        -- 最初に真になった WHEN の THEN の値を返した時点で
        -- その CASE 式全体の結果が確定する。
        --
        -- したがって、後ろに同時に真になりうる条件があっても、
        -- 最初に一致した条件が優先される。

        WHEN warehouse_id IN (1, 2) THEN 'New York'
        -- 最初の条件である。
        --
        -- warehouse_id が 1 または 2 の場合に
        -- city として 'New York' を返す。
        --
        -- ここで重要なのは、
        -- warehouse_id = 2 もこの条件に含まれている点である。
        --
        -- つまり warehouse_id = 2 の行は、
        -- この時点で条件成立となり、
        -- CASE 式の結果が 'New York' に確定する。
        --
        -- そのため、その後ろに書かれている
        --   WHEN warehouse_id = 2 THEN 'New Jersey'
        -- は、warehouse_id = 2 に対しては評価されない。
        --
        -- これがこのSQLで示したい「短絡評価」の本質である。
        --
        -- 実際の対応としては
        --   warehouse_id = 1 -> New York
        --   warehouse_id = 2 -> New York
        -- になる。

        WHEN warehouse_id = 2 THEN 'New Jersey'
        -- warehouse_id が 2 のとき 'New Jersey' を返したい
        -- ように見える条件である。
        --
        -- しかし、実際には warehouse_id = 2 の行は
        -- 1つ前の
        --   WHEN warehouse_id IN (1, 2)
        -- で既に真になっている。
        --
        -- CASE 式は最初に一致した条件で終了するため、
        -- この WHEN は warehouse_id = 2 に対して到達しない。
        --
        -- したがって、この行は実質的に
        -- 「死んだ条件」「到達不能な条件」
        -- になっている。
        --
        -- 学習上とても重要な点は、
        -- CASE 式では「後ろにより具体的な条件があっても、
        -- 前のより広い条件に含まれていれば意味を失う」
        -- ということである。
        --
        -- もし本当に warehouse_id = 2 を 'New Jersey' にしたいなら、
        -- 条件の順番を入れ替えて、
        --
        --   WHEN warehouse_id = 2 THEN 'New Jersey'
        --   WHEN warehouse_id IN (1, 2) THEN 'New York'
        --
        -- のように、より具体的な条件を先に書く必要がある。

        WHEN warehouse_id = 3 THEN 'Los Angels'
        -- warehouse_id が 3 の場合は 'Los Angels' を返す。
        --
        -- ここは前の条件に含まれていないため、
        -- warehouse_id = 3 の行ではこの条件が初めて真になり、
        -- city は 'Los Angels' になる。
        --
        -- なお、一般的な表記としては
        -- 'Los Angeles' の可能性が高いため、
        -- 実データで使う場合はスペル確認が必要である。

        WHEN warehouse_id = 4 THEN 'Seattle'
        -- warehouse_id が 4 の場合は 'Seattle' を返す。

        WHEN warehouse_id = 5 THEN 'San Francisco'
        -- warehouse_id が 5 の場合は 'San Francisco' を返す。

        ELSE NULL
        -- 上記いずれの条件にも一致しなかった場合の戻り値である。
        --
        -- たとえば warehouse_id = 6 や 10 など、
        -- 今回の分岐で定義していない値が来た場合は NULL になる。
        --
        -- ELSE を省略しても、多くの場合は一致しなければ NULL になるが、
        -- 今回は動作を明示するために ELSE NULL と書いている。
    END AS city,
    -- CASE 式全体の評価結果に city という列名を付けている。
    -- したがって、SELECT結果ではこの導出値が city 列として表示される。

    region
    -- 元の region 列もそのまま表示する。
    --
    -- よって最終結果は、
    -- warehouse_id をもとに計算した city と
    -- 元の region を並べて返す形になる。

FROM Warehouse;
-- 検索対象のテーブルは Warehouse である。
--
-- SQLは集合指向で動くため、
-- 実際には Warehouse テーブルのすべての行に対して
-- この CASE 式が適用される。
--
-- 1行ごとに考えると、
-- warehouse_id を見て city を決める処理を
-- 全行に繰り返していると理解すると分かりやすい。

-- ============================================
-- このSQLのアルゴリズム
-- ============================================
--
-- 各行に対して、処理は次の順で進む。
--
-- 1. Warehouse テーブルから1行を対象にする
-- 2. その行の warehouse_id を取得する
-- 3. CASE 式の WHEN 条件を上から順に評価する
-- 4. 最初に真になった条件の THEN の値を city として返す
-- 5. どれにも一致しなければ NULL を返す
-- 6. city と region を結果として出力する
--
-- 特に重要なのは 3 と 4 である。
--
-- CASE 式は「複数の条件を全部調べて最後に選ぶ」のではなく、
-- 「上から見て最初に一致した条件で終了する」。
--
-- したがって、このSQLの実際の対応関係は次のようになる。
--
--   warehouse_id = 1 -> New York
--   warehouse_id = 2 -> New York
--   warehouse_id = 3 -> Los Angels
--   warehouse_id = 4 -> Seattle
--   warehouse_id = 5 -> San Francisco
--   その他         -> NULL
--
-- ここで重要なのは、
--
--   warehouse_id = 2 -> New Jersey
--
-- ではない、という点である。
--
-- 理由は、warehouse_id = 2 は最初の条件
--
--   warehouse_id IN (1, 2)
--
-- で既に捕まってしまうからである。

-- ============================================
-- なぜ「短絡評価」と言えるのか
-- ============================================
--
-- 短絡評価という言葉は、
-- 条件が確定したら残りを評価しない、という意味で使われる。
--
-- このCASE式では、
-- warehouse_id = 2 の行を例にすると流れは次のようになる。
--
--   1. WHEN warehouse_id IN (1, 2) を評価
--      -> 真
--   2. THEN 'New York' を返す
--   3. CASE 式終了
--   4. 以降の WHEN warehouse_id = 2 は見ない
--
-- このように、最初の一致で結果が確定し、
-- 残りの条件は実質的に無視される。
--
-- この性質があるため、CASE 式では
-- 条件の「順番」が非常に重要になる。
--
-- 特に、
--   広い条件
--   具体的な条件
-- を混在させる場合には注意が必要である。
--
-- 今回の最初の条件
--
--   warehouse_id IN (1, 2)
--
-- は比較的広い条件であり、
-- その後の
--
--   warehouse_id = 2
--
-- を含んでしまっている。
--
-- このため、後ろの具体条件が意味を持てなくなっている。

-- ============================================
-- 条件の順番を直すとどうなるか
-- ============================================
--
-- もし warehouse_id = 2 のときに本当に
-- 'New Jersey' を返したいなら、
-- より具体的な条件を先に書く必要がある。
--
-- 例:
--
-- CASE
--     WHEN warehouse_id = 2 THEN 'New Jersey'
--     WHEN warehouse_id IN (1, 2) THEN 'New York'
--     WHEN warehouse_id = 3 THEN 'Los Angels'
--     WHEN warehouse_id = 4 THEN 'Seattle'
--     WHEN warehouse_id = 5 THEN 'San Francisco'
--     ELSE NULL
-- END
--
-- このようにすると、
-- warehouse_id = 2 の行は最初の条件で確定し、
-- 'New Jersey' が返る。
--
-- 一方、warehouse_id = 1 は 2 ではないため次に進み、
-- IN (1, 2) の条件で 'New York' が返る。
--
-- つまり CASE 式では、
-- 「より限定的な条件を先に、より広い条件を後に」
-- 置くのが基本である。

-- ============================================
-- 実務上の注意
-- ============================================
--
-- 1. 条件が重複していないか確認すること
--    今回のように、前の条件が後ろの条件を含んでいると、
--    後ろの条件が到達不能になる。
--
-- 2. CASE 式は上から順で意味が決まることを意識すること
--    順番を変えるだけで結果が変わる場合がある。
--
-- 3. 分岐が増えるならマスタテーブル化も検討すること
--    都市対応が多くなる場合は、CASE 式で列挙するより
--    別テーブルに対応関係を持たせて JOIN する方が保守しやすい。
--
-- 4. 返却値の表記確認も重要である
--    'Los Angels' など、値そのものの正しさも
--    SQLの品質に直結する。
