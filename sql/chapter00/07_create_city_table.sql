-- ============================================
-- ファイル名: 07_create_city_table.sql
-- 目的:
--   都市名と人口を管理するための City テーブルを作成し、
--   サンプルデータを登録する。
--
-- 概要:
--   このテーブルは、各都市を1行で表し、
--   city 列に都市名、population 列に人口を保持する。
--
--   その後の PIVOT 処理では、この縦持ちのデータ
--   （1行に1都市ずつ入っている形）を、
--   横持ちのデータ
--   （1行の中に複数都市を列として並べる形）
--   に変換する。
-- ============================================

CREATE TABLE City
(
    city CHAR(32) NOT NULL,
    -- city 列は都市名を表す。
    --
    -- CHAR(32) は「固定長文字列」であり、
    -- 常に32文字分の領域を使う。
    --
    -- たとえば 'New York' のような短い文字列でも、
    -- 内部的には固定長として扱われる。
    --
    -- 学習用としては問題ないが、実務では
    -- 都市名の長さが可変であることが多いため、
    -- VARCHAR を使う設計もよくある。
    --
    -- NOT NULL により、都市名を必ず入れる必要がある。
    -- つまり city が NULL の行は許可されない。

    population INTEGER NOT NULL,
    -- population 列は都市の人口を表す。
    --
    -- INTEGER 型なので整数値として保持される。
    -- 人口は小数ではなく整数で表すのが自然なので、
    -- この型選択は妥当である。
    --
    -- NOT NULL により、人口が未設定の行は登録できない。

    CONSTRAINT pk_City PRIMARY KEY (city)
    -- city 列を主キーとして定義している。
    --
    -- 主キーには次の意味がある。
    --
    -- 1. 一意性
    --    同じ city を2回登録できない。
    --    たとえば 'New York' を重複して登録するとエラーになる。
    --
    -- 2. 非NULL制約
    --    主キー列は NULL を取れない。
    --    今回は NOT NULL も明示しているので意味がより分かりやすい。
    --
    -- この設計により、
    -- 「1都市につき1行だけ存在する」
    -- という表現になっている。
);


INSERT INTO City VALUES ('New York', 8460000);
-- New York の人口を登録する。
-- 1行が「1都市の人口レコード」である。

INSERT INTO City VALUES ('Los Angels', 3840000);
-- Los Angels の人口を登録する。
--
-- 注意:
-- 一般的には 'Los Angeles' と表記されることが多い。
-- サンプル通りに登録しているが、
-- 実データとして使う場合はスペル確認が必要である。

INSERT INTO City VALUES ('San Francisco', 815000);
-- San Francisco の人口を登録する。

INSERT INTO City VALUES ('New Orleans', 377000);
-- New Orleans の人口を登録する。

-- ============================================
-- このテーブル構造の意味
-- ============================================
--
-- 現在の City テーブルは「縦持ち」の構造である。
--
-- イメージ:
--
--   city            | population
--   ----------------+-----------
--   New York        | 8460000
--   Los Angels      | 3840000
--   San Francisco   | 815000
--   New Orleans     | 377000
--
-- これはリレーショナルデータベースで最も自然な表現の1つであり、
-- 「都市ごとの人口」という事実を1行ずつ格納している。
--
-- このあと行う PIVOT は、この縦持ちデータを
--
--   New York | Los Angels | San Francisco | New Orleans
--   ---------+------------+---------------+------------
--   8460000  | 3840000    | 815000        | 377000
--
-- のような横持ち形式へ変換する処理である。
